-- =========================================================
-- 1. USERS
-- =========================================================

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(150) NOT NULL,
    position VARCHAR(150) NOT NULL,
    username VARCHAR(100) NOT NULL,
    password_hash TEXT NOT NULL,

    role VARCHAR(20) NOT NULL DEFAULT 'USER'
        CHECK (role IN ('ADMIN', 'USER')),

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Username case-insensitive.
-- "admin" dan "ADMIN" dianggap username yang sama.
CREATE UNIQUE INDEX uq_users_username_lower
    ON users (LOWER(username));

CREATE INDEX idx_users_status
    ON users (status);

CREATE INDEX idx_users_role
    ON users (role);



-- =========================================================
-- 2. QUESTION TEMPLATES
-- Template dasar berdasarkan relationship.
-- =========================================================

CREATE TABLE question_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(150) NOT NULL,

    relationship_type VARCHAR(30) NOT NULL
        CHECK (
            relationship_type IN (
                'SELF',
                'MANAGER',
                'PEER',
                'SUBORDINATE'
            )
        ),

    description TEXT,

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- V1: satu template utama untuk masing-masing hubungan.
    CONSTRAINT uq_question_templates_relationship
        UNIQUE (relationship_type)
);



-- =========================================================
-- 3. TEMPLATE QUESTIONS
-- Pertanyaan yang ada di master template.
-- =========================================================

CREATE TABLE template_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    template_id BIGINT NOT NULL
        REFERENCES question_templates(id)
        ON DELETE CASCADE,

    question_text TEXT NOT NULL,

    question_type VARCHAR(30) NOT NULL
        CHECK (
            question_type IN (
                'RATING_1_5',
                'ESSAY'
            )
        ),

    sort_order INTEGER NOT NULL
        CHECK (sort_order > 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_template_questions_template
    ON template_questions(template_id, sort_order);



-- =========================================================
-- 4. PERFORMANCE REVIEWS
-- Master dari setiap Performance Review.
-- =========================================================

CREATE TABLE performance_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    title VARCHAR(255) NOT NULL,
    description TEXT,

    -- Absolute timestamps. Display timezone is handled by the client.
    -- Review activity is allowed when:
    -- start_at <= database_time < end_at
    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,

    status VARCHAR(30) NOT NULL DEFAULT 'OPEN'
        CHECK (
            status IN (
                'OPEN',
                'IN_PROGRESS',
                'CLOSED'
            )
        ),

    created_by BIGINT NOT NULL
        REFERENCES users(id)
        ON DELETE RESTRICT,

    closed_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_performance_review_dates
        CHECK (end_at > start_at)
);

CREATE INDEX idx_performance_reviews_status
    ON performance_reviews(status);

CREATE INDEX idx_performance_reviews_dates
    ON performance_reviews(start_at, end_at);



-- =========================================================
-- 5. PERFORMANCE REVIEW QUESTIONS
--
-- Snapshot pertanyaan.
--
-- Template hanya sumber awal.
-- Begitu review dibuat, pertanyaan disalin ke sini.
--
-- Perubahan template di masa depan TIDAK mengubah review lama.
-- =========================================================

CREATE TABLE performance_review_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    performance_review_id BIGINT NOT NULL
        REFERENCES performance_reviews(id)
        ON DELETE RESTRICT,

    relationship_type VARCHAR(30) NOT NULL
        CHECK (
            relationship_type IN (
                'SELF',
                'MANAGER',
                'PEER',
                'SUBORDINATE'
            )
        ),

    question_text TEXT NOT NULL,

    question_type VARCHAR(30) NOT NULL
        CHECK (
            question_type IN (
                'RATING_1_5',
                'ESSAY'
            )
        ),

    sort_order INTEGER NOT NULL
        CHECK (sort_order > 0),

    -- Hanya untuk trace asal template.
    -- Snapshot text/type tetap tersimpan di tabel ini.
    source_template_question_id BIGINT
        REFERENCES template_questions(id)
        ON DELETE SET NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_review_questions_review_relationship
    ON performance_review_questions(
        performance_review_id,
        relationship_type,
        sort_order
    );



-- =========================================================
-- 6. REVIEW ASSIGNMENTS
--
-- Menentukan:
-- siapa menilai siapa,
-- dan hubungannya apa.
-- =========================================================

CREATE TABLE review_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    performance_review_id BIGINT NOT NULL
        REFERENCES performance_reviews(id)
        ON DELETE RESTRICT,

    reviewer_user_id BIGINT NOT NULL
        REFERENCES users(id)
        ON DELETE RESTRICT,

    reviewee_user_id BIGINT NOT NULL
        REFERENCES users(id)
        ON DELETE RESTRICT,

    relationship_type VARCHAR(30) NOT NULL
        CHECK (
            relationship_type IN (
                'SELF',
                'MANAGER',
                'PEER',
                'SUBORDINATE'
            )
        ),

    status VARCHAR(30) NOT NULL DEFAULT 'NOT_STARTED'
        CHECK (
            status IN (
                'NOT_STARTED',
                'DRAFT',
                'SUBMITTED'
            )
        ),

    started_at TIMESTAMPTZ,
    submitted_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Reviewer tidak boleh dua kali menilai orang yang sama
    -- dalam Performance Review yang sama.
    CONSTRAINT uq_review_assignment
        UNIQUE (
            performance_review_id,
            reviewer_user_id,
            reviewee_user_id
        ),

    -- SELF harus dirinya sendiri.
    -- Selain SELF tidak boleh dirinya sendiri.
    CONSTRAINT chk_review_assignment_relationship
        CHECK (
            (
                relationship_type = 'SELF'
                AND reviewer_user_id = reviewee_user_id
            )
            OR
            (
                relationship_type <> 'SELF'
                AND reviewer_user_id <> reviewee_user_id
            )
        ),

    -- Kalau sudah SUBMITTED, submitted_at harus ada.
    CONSTRAINT chk_review_assignment_submission
        CHECK (
            status <> 'SUBMITTED'
            OR submitted_at IS NOT NULL
        )
);

CREATE INDEX idx_review_assignments_review
    ON review_assignments(performance_review_id);

CREATE INDEX idx_review_assignments_reviewer
    ON review_assignments(reviewer_user_id);

CREATE INDEX idx_review_assignments_reviewee
    ON review_assignments(reviewee_user_id);

CREATE INDEX idx_review_assignments_status
    ON review_assignments(status);



-- =========================================================
-- 7. REVIEW ANSWERS
-- =========================================================

CREATE TABLE review_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    review_assignment_id BIGINT NOT NULL
        REFERENCES review_assignments(id)
        ON DELETE RESTRICT,

    review_question_id BIGINT NOT NULL
        REFERENCES performance_review_questions(id)
        ON DELETE RESTRICT,

    rating_value SMALLINT,

    essay_value TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Satu pertanyaan hanya boleh punya satu jawaban
    -- untuk sebuah assignment.
    CONSTRAINT uq_review_answer
        UNIQUE (
            review_assignment_id,
            review_question_id
        ),

    CONSTRAINT chk_review_answer_rating
        CHECK (
            rating_value IS NULL
            OR rating_value BETWEEN 1 AND 5
        ),

    -- Satu row jawaban harus rating ATAU essay.
    CONSTRAINT chk_review_answer_value
        CHECK (
            (
                rating_value IS NOT NULL
                AND essay_value IS NULL
            )
            OR
            (
                rating_value IS NULL
                AND essay_value IS NOT NULL
                AND LENGTH(BTRIM(essay_value)) > 0
            )
        )
);

CREATE INDEX idx_review_answers_assignment
    ON review_answers(review_assignment_id);

CREATE INDEX idx_review_answers_question
    ON review_answers(review_question_id);



